"""
Hallucination Detection and Medical Response Safety Verification Module.

Provides confidence scoring, hallucination risk classification, and safety warning
generation for medical responses generated by AI in Swasthya Sathi AI.
"""

from dataclasses import dataclass, field
import os
import re
from typing import Any, Dict, List, Optional


@dataclass
class DetectionResult:
    """Represents the outcome of a medical response hallucination risk assessment."""

    is_flagged: bool
    confidence_score: float
    risk_level: str  # "LOW", "MEDIUM", "HIGH"
    flagged_reasons: List[str] = field(default_factory=list)
    warning_message: Optional[str] = None
    breakdown: Dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "is_flagged": self.is_flagged,
            "confidence_score": round(self.confidence_score, 2),
            "risk_level": self.risk_level,
            "flagged_reasons": self.flagged_reasons,
            "warning_message": self.warning_message,
            "breakdown": self.breakdown,
        }


class HallucinationDetectorConfig:
    """Configuration thresholds and parameters for hallucination detection."""

    def __init__(
        self,
        high_risk_threshold: Optional[float] = None,
        flag_threshold: Optional[float] = None,
        require_disclaimer: Optional[bool] = None,
    ):
        # Environment variables with sensible defaults
        self.high_risk_threshold = (
            high_risk_threshold
            if high_risk_threshold is not None
            else float(os.getenv("HALLUCINATION_HIGH_RISK_THRESHOLD", "0.45"))
        )
        self.flag_threshold = (
            flag_threshold
            if flag_threshold is not None
            else float(os.getenv("HALLUCINATION_FLAG_THRESHOLD", "0.70"))
        )
        self.require_disclaimer = (
            require_disclaimer
            if require_disclaimer is not None
            else os.getenv("HALLUCINATION_REQUIRE_DISCLAIMER", "true").lower() in ("true", "1", "yes")
        )


# Patterns indicating clinical/medical queries and risky/unsubstantiated claims
MEDICAL_KEYWORDS = [
    r"\bmedicin(e|es|ation)\b", r"\bdos(e|age|ing)\b", r"\btablet(s)?\b", r"\bsyrup\b",
    r"\binjection\b", r"\btreatment\b", r"\bsymptom(s)?\b", r"\bdisease\b",
    r"\binfection\b", r"\bfever\b", r"\bpain\b", r"\bcough\b", r"\bcure\b",
    r"\bprescri(be|ption)\b", r"\bdiagnosis\b", r"\bbp\b", r"\bblood pressure\b",
    r"\bdiabetes\b", r"\bpregnant|pregnancy\b", r"\bvaccin(e|ation)\b",
    r"\bdawa\b", r"\bilaj\b", r"\bbimari\b", r"\bbukhar\b", r"\bdard\b"
]

RISKY_PHRASES = [
    r"100%\s*(guarantee[s]?|cure[s]?|safe|effective)",
    r"instant(ly)?\s*cure[s]?",
    r"cure[s]?\s+\w+\s+instantly",
    r"miracle\s*(cure|drug|treatment)",
    r"no\s*side\s*effects?",
    r"definitely\s*cure[s]?",
    r"completely\s*safe\s*for\s*everyone",
    r"no\s*need\s*to\s*(consult|see)\s*a?\s*doctor",
    r"stop\s*(taking\s*)?your\s*prescribed",
    r"take\s*\d+\s*(tablets?|pills?|spoons?)\s*every\s*(hour|minute)",
    r"exact\s*dose:\s*\d+\s*mg"
]

HEDGING_KEYWORDS = [
    r"\bconsult\s*(a\s*)?(physician|doctor|healthcare\s*provider|specialist)\b",
    r"\bmay\s*indicat(e|ing)\b",
    r"\bpossible\s*(cause|symptom|reason)\b",
    r"\bgeneral\s*(guidance|information)\b",
    r"\btypical(ly)?\b",
    r"\bseek\s*(immediate\s*)?medical\s*(attention|advice)\b",
    r"\bdaktar\s*se\s*salah\b",
    r"\bchikitshak\b"
]

DISCLAIMER_KEYWORDS = [
    r"\bnot\s*(a\s*)?(substitute\s*for|replacement\s*for)\s*(professional\s*)?medical\s*advice\b",
    r"\bconsult\s*(your\s*)?(doctor|physician|healthcare\s*professional)\b",
    r"\bfor\s*informational\s*purposes\s*only\b",
    r"\bemergency\b",
    r"\bmedical\s*disclaimer\b"
]


class MedicalHallucinationDetector:
    """
    Detector that analyzes an AI medical response against context and clinical safety rules.
    """

    def __init__(self, config: Optional[HallucinationDetectorConfig] = None):
        self.config = config or HallucinationDetectorConfig()
        self._med_patterns = [re.compile(p, re.IGNORECASE) for p in MEDICAL_KEYWORDS]
        self._risky_patterns = [re.compile(p, re.IGNORECASE) for p in RISKY_PHRASES]
        self._hedge_patterns = [re.compile(p, re.IGNORECASE) for p in HEDGING_KEYWORDS]
        self._disclaimer_patterns = [re.compile(p, re.IGNORECASE) for p in DISCLAIMER_KEYWORDS]

    def is_medical_query(self, query: str, response: str) -> bool:
        """Determines if either query or response involves clinical/health domain advice."""
        combined = f"{query} {response}"
        return any(p.search(combined) for p in self._med_patterns)

    def compute_claim_risk_score(self, response: str) -> tuple[float, List[str]]:
        """Scans for unsupported/dangerous claims and returns a penalty deduction and reasons."""
        penalty = 0.0
        reasons = []
        for p in self._risky_patterns:
            matches = p.findall(response)
            if matches:
                penalty += 0.35
                reasons.append(f"Unsubstantiated or dangerous absolute claim detected: '{p.pattern}'")
        return min(penalty, 0.85), reasons

    def compute_context_grounding_score(self, response: str, context: Optional[str]) -> tuple[float, List[str]]:
        """
        Evaluates lexical overlap and grounding when reference context is provided (e.g. RAG docs).
        """
        if not context or not context.strip():
            # If no context is expected/provided, assume baseline neutral score
            return 0.75, []

        reasons = []
        # Remove common functional stopwords before comparing content overlap
        stopwords = {
            "this", "that", "with", "from", "your", "should", "take", "adults",
            "every", "hours", "hour", "have", "about", "what", "when", "where"
        }
        resp_words = {w for w in re.findall(r"\b[a-zA-Z]{4,}\b", response.lower()) if w not in stopwords}
        ctx_words = {w for w in re.findall(r"\b[a-zA-Z]{4,}\b", context.lower()) if w not in stopwords}

        if not resp_words:
            return 0.5, ["Response contains insufficient substantive words for grounding."]

        overlap = resp_words.intersection(ctx_words)
        ratio = len(overlap) / len(resp_words)

        if ratio < 0.25:
            reasons.append(f"Low semantic overlap ({ratio:.1%}) with verified clinical context/RAG sources.")
            return min(ratio, 0.35), reasons

        return min(0.3 + (ratio * 0.7), 1.0), reasons


    def check_clinical_hedging_and_disclaimer(
        self, response: str, is_med: bool
    ) -> tuple[float, bool, List[str]]:
        """Checks for professional guidance, hedging, and disclaimers in medical answers."""
        reasons = []
        has_disclaimer = any(p.search(response) for p in self._disclaimer_patterns)
        has_hedging = any(p.search(response) for p in self._hedge_patterns)

        modifier = 0.0
        if is_med:
            if has_disclaimer:
                modifier += 0.10
            elif self.config.require_disclaimer:
                modifier -= 0.15
                reasons.append("Medical response is missing a standard clinical advisory or disclaimer.")

            if has_hedging:
                modifier += 0.05
            else:
                modifier -= 0.05

        return modifier, has_disclaimer, reasons

    def analyze(
        self,
        query: str,
        response: str,
        context: Optional[str] = None,
        retrieval_score: Optional[float] = None,
    ) -> DetectionResult:
        """
        Analyzes a query/response pair and optional RAG context for hallucination signals.
        """
        is_med = self.is_medical_query(query, response)
        flagged_reasons = []

        # 1. Base confidence
        base_confidence = 0.85

        # 2. Context Grounding / Retrieval Confidence
        if retrieval_score is not None:
            grounding_score = max(0.0, min(retrieval_score, 1.0))
            if grounding_score < 0.5:
                flagged_reasons.append(f"Low retrieval confidence score ({grounding_score:.2f}) from knowledge base.")
        else:
            grounding_score, g_reasons = self.compute_context_grounding_score(response, context)
            flagged_reasons.extend(g_reasons)

        # 3. Dangerous claims penalty
        risk_penalty, r_reasons = self.compute_claim_risk_score(response)
        flagged_reasons.extend(r_reasons)

        # 4. Hedging & Disclaimer modifier
        disc_mod, has_disc, d_reasons = self.check_clinical_hedging_and_disclaimer(response, is_med)
        flagged_reasons.extend(d_reasons)

        # Combined Confidence Calculation
        if context or (retrieval_score is not None):
            weighted_conf = (0.35 * base_confidence) + (0.45 * grounding_score) - risk_penalty + disc_mod
        else:
            weighted_conf = base_confidence - risk_penalty + disc_mod

        confidence_score = max(0.05, min(weighted_conf, 0.99))

        # Risk Classification
        if confidence_score < self.config.high_risk_threshold or risk_penalty >= 0.35:
            risk_level = "HIGH"
            is_flagged = True
        elif confidence_score < self.config.flag_threshold or len(flagged_reasons) > 0:
            risk_level = "MEDIUM"
            is_flagged = True
        else:
            risk_level = "LOW"
            is_flagged = False

        # Build user-friendly warning message
        warning_message = None
        if is_flagged:
            if risk_level == "HIGH":
                warning_message = (
                    "⚠️ Critical Advisory: This response contains unverified medical claims or unsupported advice. "
                    "Do not make health decisions based on this output. Consult a qualified physician."
                )
            else:
                warning_message = (
                    "ℹ️ Medical Caution: This information is AI-generated and may not be fully grounded in clinical guidelines. "
                    "Always verify with a licensed healthcare provider."
                )

        return DetectionResult(
            is_flagged=is_flagged,
            confidence_score=confidence_score,
            risk_level=risk_level,
            flagged_reasons=flagged_reasons,
            warning_message=warning_message,
            breakdown={
                "is_medical_domain": is_med,
                "grounding_score": round(grounding_score, 2),
                "risk_penalty": round(risk_penalty, 2),
                "has_disclaimer": has_disc,
            },
        )


# Module singleton instance with default configurations
default_detector = MedicalHallucinationDetector()


def detect_hallucination(
    query: str,
    response: str,
    context: Optional[str] = None,
    retrieval_score: Optional[float] = None,
) -> DetectionResult:
    """Convenience helper to inspect an AI response using the default detector."""
    return default_detector.analyze(
        query=query,
        response=response,
        context=context,
        retrieval_score=retrieval_score,
    )
