import jsPDF from "jspdf";
import { registerUnicodeFonts } from "../assets/fonts/notoSansDevanagariFonts";

/**
 * Cleans markdown and unsupported symbols from text for PDF rendering
 * while preserving Unicode / Devanagari text.
 */
export function cleanReportText(text = "") {
  if (!text) return "";
  return text
    .normalize("NFC")
    .replace(/\*\*/g, "")
    .replace(/__/g, "")
    .replace(/`/g, "")
    .replace(/#{1,6}\s?/g, "")
    .replace(/✅/g, "[OK]")
    .replace(/❌/g, "[X]")
    .replace(/⚠️/g, "[!]")
    .replace(/⚠/g, "[!]")
    .replace(/[\u{1F300}-\u{1FAFF}\u{2600}-\u{27BF}]/gu, "")
    .replace(/[\uFE00-\uFE0F]/gu, "")
    .replace(/✔/g, "-")
    .replace(/•/g, "-")
    .trim();
}

/**
 * Checks if a line is a heading/section label
 */
export function isHeadingLine(line = "") {
  const trimmed = line.trim();
  return (
    line.includes("Worker") ||
    line.includes("Status") ||
    line.includes("Recommendation") ||
    line.includes("Result") ||
    line.includes("Attendance") ||
    line.includes("Summary") ||
    line.includes("Report") ||
    line.includes("कार्यकर्ता") ||
    line.includes("स्थिति") ||
    line.includes("सिफारिश") ||
    line.includes("अनुशंसा") ||
    line.includes("परिणाम") ||
    line.includes("उपस्थिति") ||
    line.includes("सारांश") ||
    line.includes("रिपोर्ट") ||
    /^[0-9]+[.)]/.test(trimmed)
  );
}

/**
 * Generates an attendance and operations PDF report with full Unicode (Hindi + English) support.
 * Uses embedded Noto Sans Devanagari / Noto Sans fonts with UTF-8 / Identity-H encoding.
 */
export function generateAttendancePDF(text = "", language = "hi", options = {}) {
  const { save = true, fileName } = options;

  const hasDevanagari = /[\u0900-\u097F]/.test(text);
  const effectiveLanguage = language === "en" && !hasDevanagari ? "en" : (language || "hi");

  const labels =
    effectiveLanguage === "en"
      ? {
          reportTitle: "Attendance & Operations Report",
          responseTitle: "AI Response",
          generated: "Generated",
          footer: "Generated by Swasthya Sathi AI",
          dept: "Bihar Health Department",
        }
      : {
          reportTitle: "उपस्थिति एवं संचालन रिपोर्ट",
          responseTitle: "एआई रिपोर्ट",
          generated: "निर्मित",
          footer: "स्वास्थ्य साथी AI द्वारा निर्मित",
          dept: "बिहार स्वास्थ्य विभाग (Bihar Health Department)",
        };

  const doc = new jsPDF("p", "mm", "a4");

  // Embed Unicode fonts (Noto Sans Devanagari / Noto Sans)
  registerUnicodeFonts(doc);

  const fontName = "NotoSansDevanagari";
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();

  let y = 20;

  // ----------------------------
  // Header banner
  // ----------------------------
  doc.setFillColor(27, 73, 101);
  doc.rect(0, 0, pageWidth, 25, "F");

  doc.setTextColor(255, 255, 255);
  doc.setFont(fontName, "bold");
  doc.setFontSize(18);
  doc.text("Swasthya Sathi AI", 15, 12);

  doc.setFontSize(10);
  doc.setFont(fontName, "normal");
  doc.text(labels.dept, 15, 19);

  y = 35;

  doc.setTextColor(0, 0, 0);

  doc.setFontSize(16);
  doc.setFont(fontName, "bold");
  doc.text(labels.reportTitle, 15, y);

  y += 10;

  doc.setFontSize(10);
  doc.setFont(fontName, "normal");
  doc.text(`${labels.generated}: ${new Date().toLocaleString()}`, 15, y);

  y += 8;
  doc.setDrawColor(200, 200, 200);
  doc.line(15, y, pageWidth - 15, y);

  y += 10;

  // ----------------------------
  // Section Title
  // ----------------------------
  doc.setFontSize(13);
  doc.setFont(fontName, "bold");
  doc.text(labels.responseTitle, 15, y);

  y += 8;

  doc.setFont(fontName, "normal");
  doc.setFontSize(11);

  // ----------------------------
  // Content rendering
  // ----------------------------
  const cleanText = cleanReportText(text);
  const paragraphs = cleanText.split("\n");

  paragraphs.forEach((para) => {
    if (!para.trim()) {
      y += 6;
      return;
    }

    const lines = doc.splitTextToSize(para, 175);

    lines.forEach((line) => {
      if (y > pageHeight - 25) {
        // Footer on previous page
        doc.setFontSize(9);
        doc.setFont(fontName, "normal");
        doc.setTextColor(120);
        doc.text(labels.footer, 15, pageHeight - 10);
        doc.text(
          `Page ${doc.internal.getCurrentPageInfo().pageNumber}`,
          pageWidth - 35,
          pageHeight - 10
        );

        doc.addPage();
        y = 20;
        doc.setFontSize(11);
        doc.setTextColor(0);
      }

      if (isHeadingLine(line)) {
        doc.setFont(fontName, "bold");
      } else {
        doc.setFont(fontName, "normal");
      }

      doc.text(line, 18, y);
      y += 6;
    });

    y += 2;
  });

  // ----------------------------
  // Final Page Footer
  // ----------------------------
  doc.setFontSize(9);
  doc.setFont(fontName, "normal");
  doc.setTextColor(120);

  doc.setDrawColor(200, 200, 200);
  doc.line(15, pageHeight - 18, pageWidth - 15, pageHeight - 18);
  doc.text(labels.footer, 15, pageHeight - 10);
  doc.text(
    `Page ${doc.internal.getCurrentPageInfo().pageNumber}`,
    pageWidth - 35,
    pageHeight - 10
  );

  if (save) {
    const finalFileName = fileName || `Swasthya-Sathi-${Date.now()}.pdf`;
    doc.save(finalFileName);
  }

  return doc;
}

export default generateAttendancePDF;
